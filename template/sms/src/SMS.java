public class SMS {
    String destino;
    String texto;

    public void setDestino(String destino) {
        this.destino = destino;
    }

    public void setTexto(String texto) {
        this.texto = texto;
    }

    public String getDestino() {
        return destino;
    }

    public String getTexto() {
        return texto;
    }
}
